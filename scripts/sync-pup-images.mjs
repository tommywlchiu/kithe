// Regenerates apps/mobile/src/ui/pupImages.ts from the images in apps/mobile/assets/pups/.
// Metro needs literal require() calls, so the map is written out by hand-free codegen.
// Run: npm run pups
import { readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'apps', 'mobile', 'assets', 'pups');
const out = join(root, 'apps', 'mobile', 'src', 'ui', 'pupImages.ts');

const BREEDS = ['beagle', 'golden', 'corgi'];
const POSES = ['thriving', 'content', 'mopey', 'sleeping', 'eating'];
const expected = BREEDS.flatMap((b) => POSES.map((p) => `${b}-${p}`));

// The extension must match the bytes: Android release builds reject a JPEG named .png.
const IMAGE = /\.(png|jpe?g)$/i;
const files = readdirSync(dir).filter((f) => IMAGE.test(f));
const fileFor = (key) => files.find((f) => f.replace(IMAGE, '') === key);
const found = expected.filter((key) => fileFor(key));
const unknown = files.filter((f) => !expected.includes(f.replace(IMAGE, '')));

const entries = found
  .map((key) => `  '${key}': require('../../assets/pups/${fileFor(key)}'),`)
  .join('\n');

writeFileSync(
  out,
  `import type { ImageSource } from 'expo-image';

import type { PupPose } from './PupArt';

// Generated by \`npm run pups\` from apps/mobile/assets/pups/. Do not edit by hand.
// Missing images fall back to the labeled placeholder card.
const images: Partial<Record<string, ImageSource>> = {
${entries}
};

export function pupImage(breed: string, pose: PupPose): ImageSource | undefined {
  return images[\`\${breed}-\${pose}\`];
}
`,
);

console.log(`Wired ${found.length} of ${expected.length} pup images.`);
const missing = expected.filter((k) => !found.includes(k));
if (missing.length) console.log(`Still missing: ${missing.join(', ')}`);
if (unknown.length) console.log(`Ignored (unexpected names): ${unknown.join(', ')}`);
